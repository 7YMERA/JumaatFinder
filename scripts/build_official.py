"""Bundle geocoded official lists into data/official.js for the app.

Usage: python3 scripts/build_official.py data/surau_jumaat_*.json > data/official.js
"""
import json
import sys

KEEP = ("name", "address", "district", "state", "lat", "lng", "precision", "source", "source_url")
rows = []
for path in sys.argv[1:]:
    rows += [{k: r.get(k) for k in KEEP} for r in json.load(open(path)) if r.get("lat")]
print("// Generated by scripts/build_official.py — do not edit by hand.")
print("// Surau officially approved for Solat Jumaat (JAIS e-Masjid / JAWI).")
print("window.JUMAAT_OFFICIAL = " + json.dumps(rows, ensure_ascii=False, indent=0) + ";")
