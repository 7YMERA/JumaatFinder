"""Bundle geocoded official lists into data/official.js for the app.

Usage: python3 scripts/build_official.py data/surau_jumaat_*.json data/masjid_*.json > data/official.js
"""
import json
import sys

KEEP = ("name", "address", "district", "state", "lat", "lng", "precision", "status", "capacity", "source", "source_url")
rows = []
for path in sys.argv[1:]:
    rows += [{k: r[k] for k in KEEP if r.get(k) is not None} for r in json.load(open(path)) if r.get("lat")]
print("// Generated by scripts/build_official.py — do not edit by hand.")
print("// Masjid and surau officially approved for Solat Jumaat (JAIS e-Masjid / JAWI).")
print("window.JUMAAT_OFFICIAL = " + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";")
